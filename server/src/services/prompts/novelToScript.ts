// 小说转剧集剧本提示词模板
// v4.0 - 集成《导演级分镜制作标准模板》：8维细节标准、扩写方法论、合规红线
import {
  DIRECTOR_8D_STANDARD,
  DIRECTOR_COMPLIANCE_RULES,
  DIRECTOR_EXPANSION_METHOD,
  DIRECTOR_EXPANSION_EXAMPLE,
} from './directorTemplate';

export interface NovelToScriptParams {
  novelContent: string;
  episodesCount?: number;
  style?: string;
}

export function novelToScriptPrompt(params: NovelToScriptParams): { systemPrompt: string; prompt: string } {
  const episodesCount = params.episodesCount || 0; // 0 表示自动检测
  const style = params.style || 'standard';

  const countInstruction = episodesCount > 0
    ? `请改编为 ${episodesCount} 集剧本`
    : `重要：如果小说内容中已经包含明确的集数标记（如"第X集"、"第X话"、"Episode X"等），请严格按照原有的集数划分提取每一集内容，不要合并或拆分。如果没有明确集数标记，请根据内容合理划分集数。`;

  const systemPrompt = `你是一位专业的影视编剧，擅长将小说改编为详细的剧集剧本。

【核心原则】
1. 严格保留原文的关键情节、人物对话、场景描写，不得删减或概括原文内容
2. 将原文的叙述性文字转化为剧本格式（场景描写+动作+对话），但内容量不能减少
3. 每集剧本不少于1500字，必须包含至少3个场景
4. 每个场景必须包含完整的场景环境层、人物姿态层、肢体与道具层、面部表情层、动作过程层、光影层、对白与声音层
5. 【剧情保真】严格遵循原文情节发展顺序，不得添加原文没有的情节，不得修改人物动机和关系
6. 【关键对话保留】原文中的重要对话必须原样保留，不得改写或概括
7. 【人物一致性】人物性格、说话风格必须与原文一致，不得OOC（Out of Character）
8. 【主题明确】每集必须有明确的主题和核心冲突，禁止无主题的流水账
9. 【角色驱动】每个场景必须有角色出场和剧情推进，禁止纯环境描写的过场；角色动作和对话是场景核心
10. 【物品线索】关键物品必须在剧情中发挥作用，在 characters 和 keyItems 中明确标注

${DIRECTOR_8D_STANDARD}

${DIRECTOR_EXPANSION_METHOD}

${DIRECTOR_EXPANSION_EXAMPLE}

${DIRECTOR_COMPLIANCE_RULES}

【输出格式】
输出为 JSON 数组，每个元素包含：
- episodeNumber: 集数（从1开始，必须与原著中的集数标记一致）
- title: 剧集标题（如果原著中有标题请保留，否则根据内容概括）
- chapterRange: 该集对应的原文章节范围，必须填写具体范围（如"第1-3章"、"第4章"、"第5-6章"），如果原文无章节标记则填写"第X集"（X为当前集数），禁止统一填"第1章"
- scriptContent: 剧本正文（Markdown 格式）
- theme: 本集主题与核心冲突（一句话概括，如"主角发现家人隐瞒的秘密，信任开始崩塌"）
- characters: 本集出场角色清单，数组格式，每个元素包含 {name, role, description}，role 为"主角/配角/反派/路人"，description 为角色在本集中的功能和关键特征
- keyItems: 本集关键物品/道具清单，数组格式，每个元素包含 {name, description, importance}，importance 为"核心/重要/背景"
- plotPoints: 剧情要点数组，列出本集的3-5个关键情节节点，每个节点包含 {event, characters, items}，characters 和 items 为该节点涉及的角色名和物品名数组

【剧本格式要求】
每集 scriptContent 必须包含：
## 场景一：[场景名称]
**环境层：** [时间、地点、空间材质、光影氛围、环境微痕迹、背景底噪，不少于80字]
**姿态层：** [每个出场人物的站位坐姿、重心位置、躯干角度、双脚状态、整体朝向]
**肢体与道具层：** [左右手动作细节、手指形态、用力程度、道具持握与摆放位置]
**表情层：** [每个人物的眉眼状态、嘴角形态、面部肌肉松紧、呼吸起伏、情绪落点]
**动作过程层：** [动作触发点、运动顺序、速度幅度、停顿位置；多人动作写明先后与时间差]
**光影层：** [主光来源与色温、光影在人物和道具上的落点、明暗对比、阴影位置]
**对白与声音层：** [保留原台词 + 环境底噪、动作音效、音量层级]
[按场景叙事顺序展开正文，动作与对白描写符合上述8维细节标准]

## 场景二：[场景名称]
...（至少3个场景）

【严格禁止】
- 禁止只输出大纲、梗概或情节摘要
- 禁止将多段对话合并为一句概括
- 禁止省略环境描写和动作描写
- 禁止每集少于1500字
- 禁止 chapterRange 统一填"第1章"或留空

只返回 JSON 数组，不要其他文字、不要 markdown 代码块标记。`;

  const prompt = `小说内容：
${params.novelContent}

${countInstruction}
风格：${style}

【改编要求】
1. 每集有明确的起承转合，保留原著核心情节和人物关系
2. 对话要符合人物性格，保留原文中的关键对话
3. 每个场景按8维细节标准完整展开：环境层（质感/光影/底噪）、姿态层、肢体与道具层、表情层、动作过程层、光影层、对白与声音层，禁止笼统描述
4. 如果原著中每集已有标题，保留原标题
5. 每集剧本不少于1500字，至少包含3个场景
6. chapterRange 必须填写该集对应的原文章节范围（如"第1-3章"），不要统一填"第1章"
7. 严格保留原文内容，不得删减或概括，将叙述转化为剧本格式但内容量保持不变
8. 遵守制作合规红线：纸张文件屏幕只展示背面或抽象色块、无文字Logo品牌；医疗仅表现状态；人物均为原创虚构；无血腥暴力、无未成年人正面出镜

【输出示例（单集结构参考，实际输出需按8维标准完整展开）】
{
  "episodeNumber": 1,
  "title": "初遇",
  "chapterRange": "第1-2章",
  "scriptContent": "## 场景一：小镇清晨\\n**环境层：** 清晨薄雾笼罩青石板路，晨光从东侧屋檐斜切而下，在潮湿地面拉出柔和光带；街边早点摊热气升腾，空气中飘着豆浆油香，远处传来一声鸡鸣。\\n**姿态层：** 李明背布包立于路中央，重心落在后脚，肩背微弓；王老伯站在摊前，双手扶桌沿，微微前倾。\\n**肢体与道具层：** 李明左手攥住布包带，指节因用力泛白；右手自然垂在身侧。王老伯右手握竹夹翻动油条，左手扶住锅沿。\\n**表情层：** 李明眉眼舒展，嘴角带着久违的浅笑；王老伯眼角细纹堆起，目光上下打量，透出欣慰。\\n**动作过程层：** 李明先停步深吸一口气，随后迈步上前；王老伯闻声抬头，动作先顿半秒再回应。\\n**光影层：** 晨光从画左斜落，照亮李明半张脸，另一侧隐在檐影中；油锅上方蒸汽被逆光勾勒出轮廓。\\n**对白与声音层：** 早点摊油锅滋滋声垫底，鸡鸣声渐远；对话音量高于环境声。\\n**王老伯：** 小明啊，好久没见你了，这次回来待多久？\\n**李明：** 王老伯早！我这次回来就不走了，想在家里做点小生意。\\n\\n## 场景二：李家老宅\\n..."
}

请以 JSON 数组格式返回所有剧集，不要包含任何其他文字。`;

  return { systemPrompt, prompt };
}

// 单集润色提示词（不改变剧情，只优化文字）
export function polishScriptPrompt(scriptContent: string): { systemPrompt: string; prompt: string } {
  const systemPrompt = `你是一位专业的剧本编辑，擅长润色剧本文字。

【润色原则】
1. 不改变原剧情、不增删情节、不改变人物关系
2. 优化文字表达，使对话更自然、场景描写更生动
3. 修正语法错误、不通顺的句子
4. 保持原有的剧本格式（场景标题、环境描写、人物对话）
5. 润色后字数不应明显减少，应保持或增加细节描写

输出为 JSON 对象，包含：
- title: 剧集标题（保留原标题或优化）
- scriptContent: 润色后的剧本正文

只返回 JSON 对象，不要其他文字。`;

  const prompt = `请润色以下剧本，不改变剧情，只优化文字表达：

${scriptContent}

请以 JSON 对象格式返回，包含 title 和 scriptContent 字段。`;

  return { systemPrompt, prompt };
}

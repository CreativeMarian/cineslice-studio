// 角色提取提示词模板
// v2.1 — 提取更多角色（5-10个），详细视觉描述，排除非人物实体

export function characterExtractPrompt(scriptContent: string): { systemPrompt: string; prompt: string } {
  const systemPrompt = `你是一位专业的影视角色分析专家。请从剧本中提取所有有台词或有重要动作的**人类角色或拟人化角色**，包括主角、配角、反派、路人等。
目标提取数量：5-10个角色（根据剧本内容灵活调整，不要遗漏重要角色）。

**重要：只提取有具体形象的人物角色，绝对不要提取以下非人物实体：**
- "系统"、"系统提示"、"系统音"、"提示音"等抽象概念
- "旁白"、"解说"、"画外音"等叙述者
- "环境"、"天气"、"场景"等背景元素
- "声音"、"音效"、"音乐"等听觉元素
- 任何没有具体人形形象的抽象概念或物体

如果剧本中出现"系统"这种概念，它不是角色，不要提取。

输出格式为 JSON 数组，每个角色包含：
- name: 角色姓名
- gender: 性别（male/female/other）
- roleType: 角色类型（protagonist主角/supporting配角/antagonist反派/extra路人）
- description: 角色身份、性格、背景描述
- visualDescription: 外貌、服装、气质等视觉描述（用于后续生成概念图，必须详细）

只返回 JSON，不要其他文字。`;

  const prompt = `剧本内容：
${scriptContent}

请提取所有角色，要求：
1. 只提取**有具体人形形象的人物角色**，目标5-10个，不要遗漏重要角色
2. **绝对不要提取**"系统"、"旁白"、"提示音"、"环境"、"声音"等非人物实体
3. 即使是只出现一次的重要配角也要提取
4. visualDescription 必须详细，包含：年龄段、发型发色、面部特征、服装风格、体态体型、标志性特征、气质
5. description 要包含性格特点和在故事中的作用
6. 按重要程度排序，主角在前，配角次之，路人最后
7. 同名角色合并，不同称呼但同一人只保留一个

请以 JSON 数组格式返回。`;

  return { systemPrompt, prompt };
}
